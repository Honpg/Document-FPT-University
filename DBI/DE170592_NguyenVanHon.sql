--b)--

SELECT N.TENKHACHHANG,N.NGAYGIAOHANG,M.MAMUCGIACONG,M.TENMUCGIACONG,C.SOLUONG,M.DONGIA, (C.SOLUONG*M.DONGIA) AS THANHTIEN
FROM CHITIET C
INNER JOIN MUCGIACONG M ON M.MAMUCGIACONG= C.MAMUCGIACONG
INNER JOIN NHATKYGC N ON N.MANKGC = C.MANKGC
GO
--c)--
SELECT TOP 1 WITH TIES A.MAMUCGIACONG,TENMUCGIACONG,SUM(SOLUONG*DONGIA) AS 'DOANH THU'
FROM DBO.MUCGIACONG A INNER JOIN DBO.CHITIET B ON A.MAMUCGIACONG = B.MAMUCGIACONG
GROUP BY A.MAMUCGIACONG,TENMUCGIACONG
ORDER BY 'DOANH THU' DESC
--d)--
SELECT  TOP 1 WITH TIES A.MANKGC,TENKHACHHANG,SUM (SOLUONG) AS 'SO LAN GIA CONG'
FROM (DBO.NHATKYGC A INNER JOIN DBO.CHITIET B ON A.MANKGC = B.MANKGC) INNER JOIN DBO.MUCGIACONG C ON B.MAMUCGIACONG = C.MAMUCGIACONG
GROUP BY A.MANKGC,TENKHACHHANG
ORDER BY 'SO LAN GIA CONG' DESC

GO

USE QL_GIACONG;
CREATE TABLE MUCGIACONG (
  MAMUCGIACONG VARCHAR(50) NOT NULL PRIMARY KEY,
  TENMUCGIACONG NVARCHAR(50) NOT NULL,
  DVT NVARCHAR(20) NOT NULL,
  DONGIA DECIMAL(18, 0) NOT NULL
);
GO

CREATE TABLE NHATKYGC (
  MANKGC VARCHAR(50) PRIMARY KEY NOT NULL,
  TENKHACHHANG NVARCHAR(50) NOT NULL,
  NGAYNHANHANG DATE NOT NULL,
  NGAYGIAOHANG DATE NOT NULL,
  PTGIAOHANG NVARCHAR(20)NOT NULL,
  DIACHI NVARCHAR(100)NULL,
  DATHANHTOAN BIT NOT NULL,
  CONSTRAINT CHEKC_NGAY_GIAO_NHAN CHECK (NGAYGIAOHANG >= NGAYNHANHANG)
);
GO

CREATE TABLE CHITIET (
  MANKGC VARCHAR(50) NOT NULL,
  MAMUCGIACONG VARCHAR(50) NOT NULL,
  SOLUONG INT NOT NULL,
  PRIMARY KEY (MANKGC, MAMUCGIACONG),
  FOREIGN KEY (MANKGC) REFERENCES NHATKYGC(MANKGC),
  FOREIGN KEY (MAMUCGIACONG) REFERENCES MUCGIACONG(MAMUCGIACONG)
);
GO

